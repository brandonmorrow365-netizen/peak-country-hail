import assert from 'node:assert/strict';
import {readFileSync,statSync} from 'node:fs';
const stormHeader=readFileSync('src/components/StormHeader.astro','utf8');
const siteHeader=readFileSync('src/components/SiteHeader.astro','utf8');
const stormMotion=readFileSync('src/scripts/header-storm.ts','utf8');
const layout=readFileSync('src/layouts/Layout.astro','utf8');
const styles=readFileSync('src/styles/global.css','utf8');
const png=readFileSync('public/brand/hero-storm-background.png');
assert.equal(png.toString('ascii',1,4),'PNG','Hero fallback must be PNG');
assert.equal(png.readUInt32BE(16),1942,'Unexpected original hero width');
assert.equal(png.readUInt32BE(20),809,'Unexpected original hero height');
assert.ok(statSync('public/brand/hero-storm-background-1942.webp').size<300_000,'Desktop WebP exceeds 300 KB');
assert.ok(statSync('public/brand/hero-storm-background-960.webp').size<100_000,'Mobile WebP exceeds 100 KB');
assert.match(stormHeader,/hero-storm-background-960\.webp 960w, \/brand\/hero-storm-background-1942\.webp 1942w/);
assert.match(stormHeader,/width="1942" height="809"/);
assert.match(stormHeader,/width="604" height="453"/);
assert.match(stormHeader,/data-storm-canvas/);
assert.match(stormHeader,/storm-cloud-layer/);
assert.match(stormHeader,/@keyframes cloud-drift/);
assert.match(stormHeader,/\.storm-picture \{ position: absolute; inset: 0;/);
assert.doesNotMatch(stormHeader,/\.storm-picture,.storm-cloud-layer/);
assert.match(stormHeader,/mask-image: linear-gradient\(#000 0%, #000 24%, transparent 43%\)/);
assert.match(stormHeader,/data-lightning/);
assert.match(stormHeader,/prefers-reduced-motion: reduce/);
for (const path of ['/auto-hail-repair/','/paintless-dent-repair/','/gallery/','/hail-tracker/','/service-area/','/about/','/get-started/']) assert.match(stormHeader,new RegExp(path.replaceAll('/','\\/')));
assert.match(stormMotion,/Fine rain at several depths/);
assert.match(stormMotion,/pathBetween/);
assert.match(stormMotion,/--header-x/);
assert.match(stormMotion,/Math\.min\(devicePixelRatio \|\| 1, 2\)/);
assert.match(stormMotion,/prefers-reduced-motion: reduce/);
assert.match(siteHeader,/aria-label="Mobile navigation"/);
assert.doesNotMatch(siteHeader,/canvas|data-lightning|storm-cloud-layer/);
assert.match(layout,/pathname === '\/' \? <StormHeader \/> : <SiteHeader \/>/);
assert.match(styles,/hero-storm-background-1942\.webp/);
assert.match(styles,/hero-storm-background-960\.webp/);
assert.match(styles,/prefers-reduced-motion: reduce/);
console.log('Validated the sharp untransformed production hero base, sky-isolated cloud motion, 2× high-DPI canvas, rain/hail, lightning, parallax, current navigation, responsive assets, compact internal-page header, and reduced-motion handling.');
